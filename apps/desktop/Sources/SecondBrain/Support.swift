import Foundation
import Security

/// Filesystem layout, per-install secrets, and small process utilities.
enum Paths {
    /// ~/Library/Application Support/SecondBrain — all user data lives here.
    static var support: URL {
        let urls = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)
        let base = urls.first ?? FileManager.default.homeDirectoryForCurrentUser
        return base.appendingPathComponent("SecondBrain", isDirectory: true)
    }

    static var postgresData: URL { support.appendingPathComponent("postgres", isDirectory: true) }
    static var data: URL { support.appendingPathComponent("data", isDirectory: true) }
    static var models: URL { support.appendingPathComponent("models", isDirectory: true) }
    static var logs: URL { support.appendingPathComponent("logs", isDirectory: true) }
    static var configEnv: URL { support.appendingPathComponent("config.env") }
    static var lockFile: URL { support.appendingPathComponent("instance.lock") }
    static var backendLog: URL { logs.appendingPathComponent("backend.log") }
    static var postgresLog: URL { logs.appendingPathComponent("postgres.log") }

    /// Bundle Resources (backend/, postgres/, web/). SECONDBRAIN_RESOURCES
    /// overrides for running from `swift run` without a bundle.
    static var resources: URL {
        if let override = ProcessInfo.processInfo.environment["SECONDBRAIN_RESOURCES"] {
            return URL(fileURLWithPath: override, isDirectory: true)
        }
        return Bundle.main.resourceURL ?? FileManager.default.currentDirectoryPath.asURL
    }

    static var backendBinary: URL { resources.appendingPathComponent("backend/secondbrain-backend") }
    static var postgresBin: URL { resources.appendingPathComponent("postgres/bin") }
    static var webDist: URL { resources.appendingPathComponent("web") }

    static func ensureDirectories() {
        let fm = FileManager.default
        for dir in [support, postgresData, data, models, logs] {
            try? fm.createDirectory(at: dir, withIntermediateDirectories: true)
        }
    }
}

enum Secrets {
    /// Create config.env with per-install secrets on first run; reuse after.
    static func ensureConfigEnv(at url: URL) {
        let fm = FileManager.default
        guard !fm.fileExists(atPath: url.path) else { return }
        let secret = randomBase64(byteCount: 48)
        // Fernet key: exactly 32 bytes, url-safe base64.
        let fernet = randomURLSafeBase64(byteCount: 32)
        let contents = """
        # Generated by Second Brain on first launch — per-install secrets.
        SECRET_KEY=\(secret)
        SECRET_ENCRYPTION_KEY=\(fernet)

        """
        fm.createFile(atPath: url.path, contents: Data(contents.utf8), attributes: [.posixPermissions: 0o600])
    }

    private static func randomBytes(_ count: Int) -> [UInt8] {
        var bytes = [UInt8](repeating: 0, count: count)
        let status = SecRandomCopyBytes(kSecRandomDefault, count, &bytes)
        if status != errSecSuccess {
            // Cryptographically weak fallback should SecRandom be unavailable;
            // mixed with timestamp/pid entropy. Never expected in practice.
            var seed = UInt64(Date().timeIntervalSince1970) ^ UInt64(getpid())
            for i in bytes.indices {
                seed = seed &* 6364136223846793005 &+ 1442695040888963407
                bytes[i] = UInt8(truncatingIfNeeded: seed >> 33)
            }
        }
        return bytes
    }

    private static func randomBase64(byteCount: Int) -> String {
        Data(randomBytes(byteCount)).base64EncodedString()
    }

    private static func randomURLSafeBase64(byteCount: Int) -> String {
        Data(randomBytes(byteCount))
            .base64EncodedString()
            .replacingOccurrences(of: "+", with: "-")
            .replacingOccurrences(of: "/", with: "_")
    }
}

enum ProcessUtil {
    /// Grab a free localhost TCP port (bind to :0, read it, release it).
    static func pickFreePort() -> UInt16 {
        var addr = sockaddr_in()
        addr.sin_family = sa_family_t(AF_INET)
        addr.sin_addr.s_addr = inet_addr("127.0.0.1")
        addr.sin_port = 0

        let fd = socket(AF_INET, SOCK_STREAM, 0)
        guard fd >= 0 else { return 8100 }
        defer { close(fd) }

        var reuse: Int32 = 1
        setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &reuse, socklen_t(MemoryLayout<Int32>.size))

        let bindResult = withUnsafePointer(to: &addr) {
            $0.withMemoryRebound(to: sockaddr.self, capacity: 1) {
                bind(fd, $0, socklen_t(MemoryLayout<sockaddr_in>.size))
            }
        }
        guard bindResult == 0 else { return 8100 }

        var bound = sockaddr_in()
        var len = socklen_t(MemoryLayout<sockaddr_in>.size)
        let nameResult = withUnsafeMutablePointer(to: &bound) {
            $0.withMemoryRebound(to: sockaddr.self, capacity: 1) {
                getsockname(fd, $0, &len)
            }
        }
        guard nameResult == 0 else { return 8100 }
        return UInt16(bigEndian: bound.sin_port)
    }

    /// Try to take an exclusive file lock; held for the process lifetime.
    /// Returns the retained fd on success (nil = another instance is running).
    static func acquireInstanceLock(at url: URL) -> Int32? {
        let fd = open(url.path, O_CREAT | O_RDWR, 0o644)
        guard fd >= 0 else { return nil }
        if flock(fd, LOCK_EX | LOCK_NB) != 0 {
            close(fd)
            return nil
        }
        return fd
    }
}

extension String {
    var asURL: URL { URL(fileURLWithPath: self) }
}
